const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const expandHome = (p) => (p === '~' ? homedir() : p.startsWith('~/') ? join(homedir(), p.slice(2)) : p);
const real = (p) => { try { return realpathSync(p); } catch { return resolve(p); } };
const fileFor = (repo, agent) => {
  const cands = AGENT_FILES[agent];
  return cands.find((rel) => existsSync(join(repo, ...rel.split('/')))) ?? cands[cands.length - 1];
};
const readOr = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : null);
const blockOf = (text) => text?.match(ROLE_BLOCK_RE)?.[0].replace(/\n*$/, '\n') ?? null;
// Reads the src= token of our own marker line (not an HTML sanitizer); a marker written without a space before its
// closing comment delimiter would glue the delimiter onto the token, so trim it by plain string comparison.
const srcOf = (text) => {
  const m = /\bsrc=(\S+)/.exec(text ?? '');
  if (!m) return null;
  const tok = m[1].endsWith('-->') ? m[1].slice(0, -3) : m[1];
  return decodeURI(tok);
};

// ── parse ──────────────────────────────────────────────────────────────────────────────────────────────────

/**
 * Roles: `## <id> — <title>`, optional legacy `agent:` / `repo:` lines, then a free-markdown body up to the next
 * `## `. An optional `### When to call` subsection feeds trigger lists and native descriptions.
 * Seats: a `## seats` section holding a `| repo | vendor | role |` table (header + separator + rows).
 */
export function parseRoles(text) {
  const roles = [];
  const errors = [];
  let seats = null;
  const chunks = text.split(/^(?=## )/m).filter((c) => c.startsWith('## '));
  for (const chunk of chunks) {
    const lines = chunk.split('\n');
    if (/^## +seats\s*$/i.test(lines[0].trim())) {
      if (seats) { errors.push('more than one "## seats" section'); continue; }
      seats = [];
      let pastSep = false;
      for (const [n, raw] of lines.slice(1).entries()) {
        const l = raw.trim();
        if (!l.startsWith('|')) continue;
        if (/^\|[\s:|-]+\|?$/.test(l)) { pastSep = true; continue; }
        if (!pastSep) continue; // header row
        const cells = l.replace(/^\||\|$/g, '').split('|').map((c) => c.trim().replace(/^`|`$/g, ''));
        if (cells.length !== 3 || cells.some((c) => !c)) { errors.push(`seats row ${n + 1}: expected "| repo | vendor | role |", got "${l}"`); continue; }
        seats.push({ repo: cells[0], agent: cells[1], role: cells[2], line: raw });
      }
      continue;
    }
    const h = /^## +([A-Za-z0-9][\w-]*)\s*(?:[—–:-]\s*(.*))?$/.exec(lines[0].trim());
    if (!h) { errors.push(`bad heading: "${lines[0].trim()}" (expected "## <id> — <title>")`); continue; }
    const meta = {};
    let i = 1;
    for (; i < lines.length; i++) {
      const l = lines[i].trim();
      if (!l) { if (Object.keys(meta).length) { i++; break; } continue; }
      const m = /^(agent|repo)\s*:\s*(.+)$/.exec(l);
      if (!m) break;
      meta[m[1]] = m[2].trim();
    }
    const body = lines.slice(i).join('\n').trim();
    const when = /^### +(?:When to call|何時叫|何时叫)\s*$([\s\S]*?)(?=^#{2,3} |(?![\s\S]))/im.exec(body)?.[1].trim() ?? '';
    const role = { id: h[1], title: (h[2] ?? '').trim() || h[1], agent: meta.agent, repo: meta.repo, body, when };
    if (role.id.toLowerCase() === 'seats') errors.push('"seats" is a reserved name, not a role id');
    if (role.agent && !AGENT_FILES[role.agent]) errors.push(`${role.id}: agent "${role.agent}" not recognized (claude, codex, gemini)`);
    if (!role.body) errors.push(`${role.id}: empty body`);
    if (roles.some((r) => r.id === role.id)) errors.push(`${role.id}: duplicate id`);
    roles.push(role);
  }
  if (!roles.length && !errors.length) errors.push('no roles found (each role starts with "## <id> — <title>")');
  return { roles, seats, errors };
}

/** Resolve seats against `home` (the repo holding ROLES.md). Legacy files (no seats table) seat each role by its own agent/repo. */
export function planSeats(roles, seats, home) {
  const errors = [];
  const byId = new Map(roles.map((r) => [r.id, r]));
  let list;
  if (seats) {
    list = seats.map((s) => ({ ...s }));
    for (const s of list) {
      if (!byId.has(s.role)) errors.push(`seats: role "${s.role}" is not defined`);
      if (!AGENT_FILES[s.agent]) errors.push(`seats: vendor "${s.agent}" not recognized (claude, codex, gemini)`);
    }
    // Legacy agent/repo lines are allowed only when they agree with a seat — never silently mixed
    for (const r of roles) {
      if (!r.agent && !r.repo) continue;
      const hit = list.some((s) => s.role === r.id && s.agent === (r.agent ?? s.agent) && real(resolve(home, expandHome(s.repo))) === real(resolve(home, expandHome(r.repo ?? '.'))));
      if (!hit) errors.push(`${r.id}: its agent/repo lines contradict the seats table — keep one source (the table)`);
    }
  } else {
    list = roles.filter((r) => r.agent).map((r) => ({ repo: r.repo ?? '.', agent: r.agent, role: r.id }));
  }
  const seen = new Map();
  for (const s of list) {
    const p = resolve(home, expandHome(s.repo));
    if (!existsSync(p) || !statSync(p).isDirectory()) { errors.push(`${s.role}: repo not found or not a directory: ${s.repo} → ${p}`); continue; }
    s.repoPath = real(p);
    const k = `${s.repoPath}\0${s.agent}`;
    if (seen.has(k)) errors.push(`${seen.get(k)} and ${s.role} are both "${s.agent}" in ${s.repoPath} — one seat per vendor per folder (an agent tells its role apart only by which instruction file it reads). Put one of them in another folder/worktree, on another vendor, or leave it on call.`);
    else seen.set(k, s.role);
  }
  return { seats: list, errors };
}

// ── render ─────────────────────────────────────────────────────────────────────────────────────────────────

const whereOf = (repoPath, here, t) => (repoPath === here ? t.here : `${basename(repoPath)} (\`${repoPath}\`)`);
const oneLine = (s) => s.replace(/\s*\n\s*[-*]?\s*/g, ' ').replace(/\s+/g, ' ').trim();

function teamLines(roles, seats, here, t, me) {
  const out = [];
  for (const r of roles) {
    const mine = seats.filter((s) => s.role === r.id);
    const when = r.when ? ` — ${t.when}: ${oneLine(r.when)}` : '';
    if (!mine.length) { out.push(`- **${r.id}** — ${r.title}: ${t.oncall}${when}`); continue; }
    for (const s of mine) {
      out.push(`- **${r.id}** — ${r.title}: ${AGENT_NAMES[s.agent]} @ ${whereOf(s.repoPath, here, t)}${s === me ? ` ${t.you}` : ''}${when}`);
    }
  }
  return out;
}

export function renderBlock(seat, roles, seats, { lang, version, src }) {
  const t = T[lang] ?? T.en;
  const role = roles.find((r) => r.id === seat.role);
  const here = seat.repoPath;
  const others = seats.filter((s) => s.repoPath === here && s.agent !== seat.agent).map((s) => `\`${fileFor(here, s.agent)}\``);
  const hasOncall = roles.some((r) => !seats.some((s) => s.role === r.id));
  return [
    `<!-- flightwake-roles:begin v${version} lang=${lang} src=${encodeURI(src)} -->`,
    t.heading(role.id, role.title, AGENT_NAMES[seat.agent]),
    '',
    t.sticky,
    t.scope,
    t.generated(src),
    ...(others.length ? [t.others([...new Set(others)].join(', '))] : []),
    '',
    role.body,
    '',
    t.team,
    ...teamLines(roles, seats, here, t, seat),
    ...(hasOncall ? ['', t.oncallHow] : []),
    '',
    t.direct,
    '<!-- flightwake-roles:end -->',
    '',
  ].join('\n');
}

export function renderCard(role, roles, seats, { lang, src }) {
  const t = T[lang] ?? T.en;
  return [
    t.cardHead(role.id, role.title),
    '',
    t.cardScope,
    t.cardSrc(src),
    '',
    role.body,
    '',
    t.team,
    ...teamLines(roles, seats, null, t, null),
    '',
    t.cardReport,
    t.guidance,
    '',
  ].join('\n');
}

// JSON string escaping is valid TOML basic-string and YAML double-quoted escaping — no user text can break out of a field
const q = (s) => JSON.stringify(s);
function renderNative(vendor, role, card, { version, src }) {
  const desc = `${role.title}${role.when ? ` — ${oneLine(role.when)}` : ''} (flightwake role; guidance, not a permission boundary)`;
  const mark = `${GEN_MARK} v${version} src=${encodeURI(src)} — edit ROLES.md and run \`npx flightwake roles apply\`; do not edit here`;
  if (vendor === 'codex') {
    return `# ${mark}\nname = ${q(`fw-${role.id}`)}\ndescription = ${q(desc)}\ndeveloper_instructions = ${q(card)}\n`;
  }
  return `---\nname: ${q(`fw-${role.id}`)}\ndescription: ${q(desc)}\n---\n<!-- ${mark} -->\n\n${card}`;
}

// ── plan & execute ─────────────────────────────────────────────────────────────────────────────────────────

const withBlock = (cur, block) => {
  if (cur === null) return block;
  if (ROLE_BLOCK_RE.test(cur)) return cur.replace(ROLE_BLOCK_RE, `${block}\n`);
  return `${block}\n${cur}`; // role goes first: it is the first thing the agent should read
};
const withoutBlock = (cur) => cur.replace(ROLE_BLOCK_RE, '');
const inAllowedDir = (rel) => Object.values(NATIVE_DIRS).some((d) => rel.startsWith(`${d}/fw-`)) && !rel.includes('..');

/**
 * Build the full write plan for a team. Nothing is written here. Every output is checked against the manifest:
 * rewritten/removed only if it still matches what flightwake generated last time, or already equals the target.
 */
export function planApply({ source, text, lang, version }) {
  const home = dirname(dirname(source));
  const { roles, seats: rawSeats, errors } = parseRoles(text);
  if (errors.length) return { errors };
  const { seats, errors: seatErrors } = planSeats(roles, rawSeats, home);
  if (seatErrors.length) return { errors: seatErrors };

  const manifestPath = join(dirname(source), MANIFEST);
  let prev = { outputs: [] };
  try { if (existsSync(manifestPath)) prev = JSON.parse(readFileSync(manifestPath, 'utf8')); } catch { return { errors: [`${manifestPath} is not valid JSON — fix or delete it (it only tracks generated files)`] }; }
  const prevHash = new Map((prev.outputs ?? []).map((o) => [`${o.repo}\0${o.path}`, o.hash]));

  const desired = new Map(); // key → { repo, path, kind, content(block or file) }
  const put = (repo, path, kind, content) => desired.set(`${repo}\0${path}`, { repo, path, kind, content });
  for (const s of seats) {
    const src = relative(s.repoPath, source);
    put(s.repoPath, fileFor(s.repoPath, s.agent), 'block', renderBlock(s, roles, seats, { lang, version, src }));
  }
  const nativeTargets = new Map();
  for (const s of seats) if (NATIVE_DIRS[s.agent]) nativeTargets.set(`${s.repoPath}\0${s.agent}`, s);
  for (const s of nativeTargets.values()) {
    const src = relative(s.repoPath, source);
    for (const r of roles) {
      // Only on-call roles become native agents. A seated role stays with its seat: a native copy would let another
      // seat spawn it locally (e.g. a pm spawning fw-coder) and bypass the team's routing and review split.
      if (seats.some((x) => x.role === r.id)) continue;
      const card = renderCard(r, roles, seats, { lang, src });
      put(s.repoPath, nativeRel(s.agent, r.id), 'file', renderNative(s.agent, r, card, { version, src }));
    }
  }

  // Candidates to clean: every instruction file in every repo we touch now or touched before, plus previous outputs
  const repos = new Set([real(home), ...seats.map((s) => s.repoPath), ...(prev.outputs ?? []).map((o) => o.repo)]);
  const actions = [];
  const conflicts = [];
  const sameSource = (repo, text) => { const s = srcOf(text); return s !== null && real(resolve(repo, s)) === real(source); };

  for (const d of desired.values()) {
    const abs = join(d.repo, ...d.path.split('/'));
    const cur = readOr(abs);
    const key = `${d.repo}\0${d.path}`;
    if (d.kind === 'block') {
      const curBlock = blockOf(cur);
      if (curBlock && !sameSource(d.repo, curBlock)) { conflicts.push(`${abs}: role block from another team (${srcOf(curBlock) ?? 'unknown source'}) — remove it or apply from that team`); continue; }
      if (curBlock === d.content) { actions.push({ act: 'same', ...d, abs }); continue; }
      if (curBlock && prevHash.has(key) && prevHash.get(key) !== sha(curBlock)) { conflicts.push(`${abs}: generated role block was edited by hand — move the edit into ROLES.md, then delete the block and re-apply`); continue; }
      actions.push({ act: cur === null ? 'add' : curBlock ? 'update' : 'insert', ...d, abs, next: withBlock(cur, d.content) });
    } else {
      if (cur === d.content) { actions.push({ act: 'same', ...d, abs }); continue; }
      if (cur !== null && !cur.includes(GEN_MARK)) { conflicts.push(`${abs}: a file you wrote already has this name — rename or remove it (flightwake will not overwrite it)`); continue; }
      if (cur !== null && !sameSource(d.repo, cur)) { conflicts.push(`${abs}: generated by another team (${srcOf(cur) ?? 'unknown source'})`); continue; }
      if (cur !== null && prevHash.has(key) && prevHash.get(key) !== sha(cur)) { conflicts.push(`${abs}: generated file was edited by hand — move the edit into ROLES.md, then delete the file and re-apply`); continue; }
      actions.push({ act: cur === null ? 'add' : 'update', ...d, abs, next: d.content });
    }
  }
  // Stale blocks: instruction files of known repos that carry this team's block but no longer have a seat
  for (const repo of repos) {
    for (const rels of Object.values(AGENT_FILES)) {
      for (const rel of rels) {
        if (desired.has(`${repo}\0${rel}`)) continue;
        const abs = join(repo, ...rel.split('/'));
        const cur = readOr(abs);
        const curBlock = blockOf(cur);
        if (!curBlock || !sameSource(repo, curBlock)) continue;
        const key = `${repo}\0${rel}`;
        if (prevHash.has(key) && prevHash.get(key) !== sha(curBlock)) { conflicts.push(`${abs}: stale role block was edited by hand — delete it yourself`); continue; }
        const next = withoutBlock(cur);
        actions.push({ act: next.trim() ? 'strip' : 'rm', repo, path: rel, kind: 'block', abs, next });
      }
    }
  }
  // Stale native files from the manifest (only inside the allowed generated dirs, only if untouched)
  for (const o of prev.outputs ?? []) {
    if (o.kind !== 'file' || desired.has(`${o.repo}\0${o.path}`)) continue;
    if (!inAllowedDir(o.path)) { conflicts.push(`manifest lists ${o.path} outside the generated agent dirs — refusing to delete it`); continue; }
    const abs = join(o.repo, ...o.path.split('/'));
    const cur = readOr(abs);
    if (cur === null) continue;
    if (!cur.includes(GEN_MARK) || sha(cur) !== o.hash) { conflicts.push(`${abs}: stale generated file was edited — delete it yourself`); continue; }
    actions.push({ act: 'rm', repo: o.repo, path: o.path, kind: 'file', abs });
  }

  const outputs = [...desired.values()].map((d) => ({ repo: d.repo, path: d.path, kind: d.kind, hash: sha(d.content) }));
  return { errors: [], conflicts, actions, manifestPath, manifest: { version: 1, source: basename(source), outputs }, roles, seats, home };
}

function execute(plan, { log, target }) {
  const failed = [];
  for (const a of plan.actions) {
    if (a.act === 'same') continue;
    try {
      if (a.act === 'rm') rmSync(a.abs);
      else { mkdirSync(dirname(a.abs), { recursive: true }); writeFileSync(a.abs, a.next); }
    } catch (e) { failed.push(`${a.abs}: ${e.message}`); }
  }
  try { writeFileSync(plan.manifestPath, JSON.stringify(plan.manifest, null, 2) + '\n'); } catch (e) { failed.push(`${plan.manifestPath}: ${e.message}`); }
  if (failed.length) log(`⚠️  partially applied — these writes failed (re-run apply after fixing; it converges):\n     ${failed.join('\n     ')}`);
  return failed.length ? 1 : 0;
}

function printPlan(plan, { log, target, dry }) {
  for (const a of plan.actions) {
    const label = a.repo === real(target) ? a.path : join(relative(target, a.repo) || '.', a.path);
    const who = a.kind === 'block' && a.act !== 'strip' && a.act !== 'rm' ? ` ← ${plan.seats.find((s) => s.repoPath === a.repo && fileFor(a.repo, s.agent) === a.path)?.role ?? ''}` : '';
    log(`  ${a.act.padEnd(6)} ${label}${who}`);
    if (dry && a.kind === 'block' && a.content && a.act !== 'same') log(`\n${a.content.replace(/^/gm, '      ')}`);
  }
}

// ── skill + cleanup helpers ────────────────────────────────────────────────────────────────────────────────

/** Find the team source: this repo's ROLES.md, or the src= of a role block already in this repo. */
function findSource(target) {
  const own = join(target, '.flightwake', 'ROLES.md');
  if (existsSync(own)) return own;
  for (const rels of Object.values(AGENT_FILES)) {
    for (const rel of rels) {
      const s = srcOf(blockOf(readOr(join(target, ...rel.split('/')))));
      if (s) return isAbsolute(s) ? s : resolve(target, s);
    }
  }
  return null;
}

export function removeRoleArtifacts(target, log) {
  for (const rels of Object.values(AGENT_FILES)) {
    for (const rel of rels) {
      const p = join(target, ...rel.split('/'));
      const cur = readOr(p);
      if (!cur || !ROLE_BLOCK_RE.test(cur)) continue;
      const next = withoutBlock(cur);
      if (next.trim()) { writeFileSync(p, next); log(`  edit ${rel} ← role block removed`); }
      else { rmSync(p); log(`  rm   ${rel} (empty after role block removal)`); }
    }
  }
  // Generated on-call agents: only files carrying the generated marker, only in the generated dirs
  for (const dir of Object.values(NATIVE_DIRS)) {
    const d = join(target, ...dir.split('/'));
    if (!existsSync(d)) continue;
    for (const f of readdirSafe(d)) {
      if (!f.startsWith('fw-')) continue;
      const p = join(d, f);
      if ((readOr(p) ?? '').includes(GEN_MARK)) { rmSync(p); log(`  rm   ${dir}/${f}`); }
    }
    try { if (!readdirSafe(d).length) rmSync(d, { recursive: true }); } catch {}
  }
  for (const base of SKILL_BASES) {
    const p = join(target, ...base.split('/'), 'fw-roles');
    if (existsSync(p)) { rmSync(p, { recursive: true }); log(`  rm   ${base}/fw-roles`); }
  }
}
function readdirSafe(d) { try { return readdirSync(d); } catch { return []; } }

/** On update: refresh the fw-roles skill wherever it is already installed (never installs it). */
export function refreshRolesSkill({ target, fwSrc, lang, noJunk, log }) {
  const src = join(fwSrc, 'addons', 'roles', ROLES_LANGS.includes(lang) ? lang : 'en', 'fw-roles');
  for (const base of SKILL_BASES) {
    const dst = join(target, ...base.split('/'), 'fw-roles');
    if (!existsSync(dst)) continue;
    rmSync(dst, { recursive: true });
    cpSync(src, dst, { recursive: true, filter: noJunk });
    log(`  update ${base}/fw-roles`);
  }
}

// ── assign: edit exactly one seats row, as authorized by the user ────────────────────────────────────────────

export function assignSeat(text, { seatRepo, vendor, roleId, add, home }) {
  const { roles, seats, errors } = parseRoles(text);
  if (errors.length) return { errors };
  if (!seats) return { errors: ['this ROLES.md has no "## seats" table (legacy format) — migrate first: ask your agent to run fw-roles and "migrate to a seats table" (it shows the full preview before writing)'] };
  if (!roles.some((r) => r.id === roleId)) return { errors: [`role "${roleId}" is not defined in ROLES.md`] };
  if (!AGENT_FILES[vendor]) return { errors: [`vendor "${vendor}" not recognized (claude, codex, gemini)`] };
  const wantPath = real(resolve(home, expandHome(seatRepo)));
  const row = seats.find((s) => s.agent === vendor && real(resolve(home, expandHome(s.repo))) === wantPath);
  if (row) {
    const cells = row.line.split('|');
    // cells: ['', repo, vendor, role, ''] (leading/trailing pipes) — replace only the role cell, keep its padding
    const idx = cells.length - (row.line.trim().endsWith('|') ? 2 : 1);
    const old = cells[idx];
    cells[idx] = old.replace(old.trim(), roleId);
    const nextLine = cells.join('|');
    const at = text.indexOf(row.line);
    return { errors: [], text: text.slice(0, at) + nextLine + text.slice(at + row.line.length), change: `${row.role} → ${roleId}` };
  }
  if (!add) return { errors: [`no seat for ${seatRepo}:${vendor} — pass --add to create it`] };
  // Append after the last table row of the seats section
  const secStart = text.search(/^## +seats\s*$/im);
  const after = text.slice(secStart);
  const nextSec = after.slice(1).search(/^## /m);
  const sec = nextSec === -1 ? after : after.slice(0, nextSec + 1);
  const lastRow = [...sec.matchAll(/^[ \t]*\|.*$/gm)].pop();
  const insertAt = secStart + lastRow.index + lastRow[0].length;
  return { errors: [], text: `${text.slice(0, insertAt)}\n| ${seatRepo} | ${vendor} | ${roleId} |${text.slice(insertAt)}`, change: `(new seat) → ${roleId}` };
}

// ── CLI ────────────────────────────────────────────────────────────────────────────────────────────────────

/**
 * Install the fw-roles skill into the given skill trees. Under a --private install the copies would show up in
 * git status, so they join the existing flightwake exclude block (addExcludes is a no-op when there is none).
 */
export function installRolesSkill({ target, fwSrc, lang, bases, noJunk, log, addExcludes }) {
  const RL = ROLES_LANGS.includes(lang) ? lang : 'en';
  const src = join(fwSrc, 'addons', 'roles', RL, 'fw-roles');
  for (const base of bases) {
    const dst = join(target, ...base.split('/'), 'fw-roles');
    const existed = existsSync(dst);
    if (existed) rmSync(dst, { recursive: true });
    mkdirSync(dirname(dst), { recursive: true });
    cpSync(src, dst, { recursive: true, filter: noJunk });
    log(`  ${existed ? 'update' : 'add '} ${base}/fw-roles`);
  }
  if (addExcludes?.(bases.map((b) => `${b}/fw-roles/`))) log('  edit .git/info/exclude ← fw-roles (private install)');
  if (RL !== lang) log(`  ℹ️  roles content ships in ${ROLES_LANGS.join(' / ')} for now — installed English`);
}

export function runRoles({ target, fwSrc, version, lang, args, log, M, noJunk, addExcludes }) {
  const pos = args.filter((a) => !a.startsWith('-'));
  const sub = pos[1] ?? 'install';
  const RL = ROLES_LANGS.includes(lang) ? lang : 'en';
  const DRY = args.includes('--dry-run');
  const err = (s) => process.stderr.write(`${s}\n`);

  if (!existsSync(join(target, '.flightwake'))) {
    (sub === 'card' ? err : log)(M({ en: '⚠️  No flightwake install here — run `npx flightwake init` first.', 'zh-TW': '⚠️  這裡沒有 flightwake 安裝 — 請先跑 `npx flightwake init`。' }));
    return 1;
  }

  if (sub === 'install') {
    const bases = ['.claude/skills', ...(['AGENTS.md', 'GEMINI.md'].some((f) => existsSync(join(target, f))) ? ['.agents/skills'] : [])];
    installRolesSkill({ target, fwSrc, lang, bases, noJunk, log, addExcludes });
    log(M({
      en: '\n✅ fw-roles installed. Ask your agent to run fw-roles: it scans the project, recommends a team, lets you preview and customize, then runs `npx flightwake roles apply`.',
      'zh-TW': '\n✅ fw-roles 已安裝。請你的 agent 跑 fw-roles:它會掃專案、推薦一組角色、讓你預覽與客製,最後跑 `npx flightwake roles apply`。',
    }));
    return 0;
  }

  if (sub === 'remove') {
    removeRoleArtifacts(target, log);
    log(M({ en: '\n✅ role blocks, generated agents and fw-roles removed from this repo. .flightwake/ROLES.md is user data and was kept.', 'zh-TW': '\n✅ 本 repo 的角色區塊、產生的 agent 與 fw-roles 已移除。.flightwake/ROLES.md 是使用者資料,保留。' }));
    return 0;
  }

  if (!['apply', 'card', 'assign'].includes(sub)) {
    log(`⚠️  unknown roles subcommand: ${sub} (install | apply [--dry-run] | card <id> | assign <repo>:<vendor> <id> [--add] [--dry-run] | remove)`);
    return 1;
  }

  const source = findSource(target);
  if (!source || !existsSync(source)) {
    (sub === 'card' ? err : log)(M({
      en: `⚠️  No .flightwake/ROLES.md here${source ? ` (block points to ${source}, which is missing)` : ''} — run the fw-roles skill to create one.`,
      'zh-TW': `⚠️  這裡沒有 .flightwake/ROLES.md${source ? `(區塊指向的 ${source} 不存在)` : ''} — 請跑 fw-roles skill 建立。`,
    }));
    return 1;
  }
  const home = dirname(dirname(source));
  const text = readFileSync(source, 'utf8');

  if (sub === 'card') {
    const id = pos[2];
    const { roles, seats: rawSeats, errors } = parseRoles(text);
    const { seats, errors: se } = errors.length ? { seats: [], errors: [] } : planSeats(roles, rawSeats, home);
    const role = roles.find((r) => r.id === id);
    if (errors.length || se.length || !role) { err(`⚠️  ${!id ? 'usage: roles card <id>' : !role ? `role "${id}" not found in ${source}` : [...errors, ...se].join('\n     ')}`); return 1; }
    process.stdout.write(renderCard(role, roles, seats, { lang: RL, src: source }));
    return 0;
  }

  let nextText = text;
  let change = null;
  if (sub === 'assign') {
    const spec = pos[2];
    const roleId = pos[3];
    const cut = spec?.lastIndexOf(':') ?? -1; // last colon: Windows drive letters stay in the path
    if (!spec || cut <= 0 || !roleId) { log('⚠️  usage: roles assign <repo>:<vendor> <role-id> [--add] [--dry-run]'); return 1; }
    const r = assignSeat(text, { seatRepo: spec.slice(0, cut), vendor: spec.slice(cut + 1), roleId, add: args.includes('--add'), home });
    if (r.errors.length) { log(`⚠️  ${r.errors.join('\n     ')}`); return 1; }
    nextText = r.text;
    change = r.change;
  }

  const plan = planApply({ source, text: nextText, lang: RL, version });
  if (plan.errors.length) { log(`⚠️  ${relative(target, source) || source}:\n     ${plan.errors.join('\n     ')}`); return 1; }
  log(`flightwake roles ${sub}${DRY ? ' --dry-run' : ''} ← ${source}${change ? `  (${change})` : ''}\n`);
  printPlan(plan, { log, target, dry: DRY });
  if (plan.conflicts.length) {
    log(`\n⚠️  ${M({ en: 'conflicts — nothing was written:', 'zh-TW': '有衝突 — 什麼都沒寫:' })}\n     ${plan.conflicts.join('\n     ')}`);
    return 1;
  }
  if (DRY) { log(M({ en: '\n(dry run — nothing written)', 'zh-TW': '\n(dry run — 未寫入任何檔案)' })); return 0; }
  if (sub === 'assign') {
    if (readFileSync(source, 'utf8') !== text) { log('⚠️  ROLES.md changed while planning (another agent?) — nothing written; re-run.'); return 1; }
    writeFileSync(source, nextText);
    log(`  edit   ${relative(target, source) || source} ← seats (${change})`);
  }
  const rc = execute(plan, { log, target });
  log(M({
    en: '\n✅ roles applied. Each agent picks its role up on its **next new session** or /clear — running sessions and workers keep their current role until then. Commit the changed files in every repo listed above.',
    'zh-TW': '\n✅ 角色已套用。每個 agent 在**下一次新對話**或 /clear 後才生效——正在跑的 session 與 worker 在那之前維持原角色。上面列到的每個 repo 都要 commit 變更的檔案。',
  }));
  return rc;
}
