/**
 * flightwake roles — opt-in add-on (not installed by init). Team roles live in one human-edited file,
 * `.flightwake/ROLES.md`: role definitions (`## <id> — <title>` + body) and, optionally, a `## seats` table that
 * puts roles on (repo, vendor) seats. A seat is rendered into the instruction file that vendor re-reads at every
 * session start (Claude Code → CLAUDE.md, Codex → AGENTS.md, Gemini CLI → GEMINI.md), so it survives /clear with
 * no hook. Every on-call role (no seat) is generated as a native agent definition in each seated (repo, vendor)
 * (`.claude/agents/fw-<id>.md`, `.codex/agents/fw-<id>.toml`); any role can be printed as a dispatch card.
 * Role text is guidance, never enforcement: nothing here claims to block a tool call (see TRAPS
 * codex-custom-agent-sandbox-not-enforced).
 *
 *   roles [install]                   install the fw-roles skill
 *   roles apply [--dry-run]           render ROLES.md into seat blocks + native definitions, clean up stale output
 *   roles card <id>                   print one role as a dispatch card (stdout only; errors → stderr, exit 1)
 *   roles assign <repo>:<vendor> <id> [--add] [--dry-run]   put a role on a seat (edits only that seats row)
 *   roles remove                      strip this repo's role blocks, generated agents and the fw-roles skill
 *
 * Ownership: a manifest next to ROLES.md (`.flightwake/roles-manifest.json`) lists every generated output with a
 * hash. Output is only rewritten or removed when it still matches what was generated (or already equals the new
 * content); anything else is a conflict, reported, and nothing is written. Zero dependencies (node: built-ins).
 */
