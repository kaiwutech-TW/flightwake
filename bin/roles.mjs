/**
 * flightwake roles — opt-in add-on (not installed by init). Team roles live in one human-edited file,
 * `.flightwake/ROLES.md`; `roles apply` renders each role into the instruction file its agent reads on every
 * session start — Claude Code → CLAUDE.md, Codex → AGENTS.md, Gemini CLI → GEMINI.md — so a role survives
 * /clear with no hook and no trust prompt. A team may span several repos: one ROLES.md, and apply writes into
 * every repo it names. The routing key is (repo, agent): one role per agent per folder.
 *
 *   roles [install]       install the fw-roles skill (scan → recommend → preview → customize → apply)
 *   roles apply [--dry-run]  render ROLES.md into instruction files (dry-run prints the blocks, writes nothing)
 *   roles remove          strip role blocks and the fw-roles skill from this repo (ROLES.md is user data, kept)
 *
 * Same rules as the core installer: zero dependencies, marker-delimited blocks, user data never overwritten.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { join, dirname, resolve, relative, basename, isAbsolute } from 'node:path';
import { homedir } from 'node:os';

export const ROLES_LANGS = ['en', 'zh-TW'];
export const ROLE_BLOCK_RE = /<!-- flightwake-roles:begin[^>]*-->[\s\S]*?<!-- flightwake-roles:end -->\n*/;
const SKILL_BASES = ['.claude/skills', '.agents/skills'];

// Where each agent reads its per-session instructions. First existing candidate wins; last is the creation target.
const AGENT_FILES = {
  claude: ['.claude/CLAUDE.md', 'CLAUDE.md'],
  codex: ['AGENTS.md'],
  gemini: ['GEMINI.md'],
};
const AGENT_NAMES = { claude: 'Claude Code', codex: 'Codex', gemini: 'Gemini CLI' };

const T = {
  en: {
    heading: (id, title, agent) => `# Your role: ${id} — ${title} (the ${agent} in this folder)`,
    sticky: 'This block is reloaded on every new session and after /clear. It overrides any impression from earlier chat.',
    generated: (src) => `Generated by \`npx flightwake roles apply\` from \`${src}\` — edit that file and re-run; do not edit here.`,
    others: (files) => `Role sections in ${files} belong to other agents in this folder — they do not apply to you.`,
    team: 'Team (one shared definition):',
    here: 'this folder',
    you: '← you',
    direct: '**Direct instructions from the user** count as a dispatch; if one conflicts with your Never list, point out the conflict and confirm first.',
  },
  'zh-TW': {
    heading: (id, title, agent) => `# 你的角色:${id} — ${title}(本資料夾的 ${agent})`,
    sticky: '本段在每次新對話與 /clear 後都會自動重新載入;以本段為準,不以聊天中的舊印象為準。',
    generated: (src) => `由 \`npx flightwake roles apply\` 從 \`${src}\` 產生——要改請改那份檔案再重跑,不要直接改這裡。`,
    others: (files) => `${files} 裡的角色段落屬於本資料夾的其他 agent,不適用於你。`,
    team: '團隊(同一份定義):',
    here: '本資料夾',
    you: '← 你',
    direct: '**使用者直接下的指令**視同派工照做;若與你的禁止事項衝突,先指出衝突並請使用者確認。',
  },
};

const expandHome = (p) => (p === '~' ? homedir() : p.startsWith('~/') ? join(homedir(), p.slice(2)) : p);
const fileFor = (repo, agent) => {
  const cands = AGENT_FILES[agent];
  const hit = cands.find((rel) => existsSync(join(repo, ...rel.split('/'))));
  return hit ?? cands[cands.length - 1];
};

/**
 * Parse ROLES.md. Everything before the first `## ` heading is free prose (ignored).
 * A role: `## <id> — <title>`, then `key: value` lines (agent, repo), then a free-markdown body up to the next `## `.
 */
export function parseRoles(text) {
  const roles = [];
  const errors = [];
  const chunks = text.split(/^(?=## )/m).filter((c) => c.startsWith('## '));
  for (const chunk of chunks) {
    const lines = chunk.split('\n');
    const h = /^## +([A-Za-z0-9][\w-]*)\s*(?:[—–:-]\s*(.*))?$/.exec(lines[0].trim());
    if (!h) { errors.push(`bad heading: "${lines[0].trim()}" (expected "## <id> — <title>")`); continue; }
    const meta = {};
    let i = 1;
    for (; i < lines.length; i++) {
      const l = lines[i].trim();
      if (!l) { if (Object.keys(meta).length) { i++; break; } continue; }
      const m = /^(agent|repo)\s*:\s*(.+)$/.exec(l);
      if (!m) break;
      meta[m[1]] = m[2].trim();
    }
    const role = { id: h[1], title: (h[2] ?? '').trim() || h[1], agent: meta.agent, repo: meta.repo ?? '.', body: lines.slice(i).join('\n').trim() };
    if (!role.agent) errors.push(`${role.id}: missing "agent:" line`);
    else if (!AGENT_FILES[role.agent]) errors.push(`${role.id}: agent "${role.agent}" not recognized (claude, codex, gemini)`);
    if (!role.body) errors.push(`${role.id}: empty body`);
    if (roles.some((r) => r.id === role.id)) errors.push(`${role.id}: duplicate id`);
    roles.push(role);
  }
  if (!roles.length && !errors.length) errors.push('no roles found (each role starts with "## <id> — <title>")');
  return { roles, errors };
}

/** Resolve repos and validate the (repo, agent) routing key. `home` = repo that holds ROLES.md. */
export function planRoles(roles, home) {
  const errors = [];
  for (const r of roles) {
    const p = expandHome(r.repo);
    r.repoPath = resolve(home, p);
    if (!existsSync(r.repoPath)) errors.push(`${r.id}: repo not found: ${r.repo} → ${r.repoPath}`);
  }
  const seen = new Map();
  for (const r of roles) {
    const k = `${r.repoPath}\0${r.agent}`;
    if (seen.has(k)) {
      errors.push(`${seen.get(k)} and ${r.id} are both "${r.agent}" in ${r.repoPath} — one role per agent per folder ` +
        '(an agent tells its role apart only by which instruction file it reads). Put one of them in another folder/worktree or on another agent.');
    } else seen.set(k, r.id);
  }
  return errors;
}

export function renderBlock(role, roles, { lang, version, src }) {
  const t = T[lang] ?? T.en;
  const here = role.repoPath;
  const others = roles
    .filter((r) => r.repoPath === here && r.agent !== role.agent)
    .map((r) => `\`${fileFor(here, r.agent)}\``);
  const team = roles.map((r) => {
    const where = r.repoPath === here ? t.here : `${basename(r.repoPath)} (\`${r.repoPath}\`)`;
    return `- **${r.id}** — ${r.title}: ${AGENT_NAMES[r.agent]} @ ${where}${r === role ? ` ${t.you}` : ''}`;
  });
  return [
    `<!-- flightwake-roles:begin v${version} lang=${lang} src=${encodeURI(src)} -->`,
    t.heading(role.id, role.title, AGENT_NAMES[role.agent]),
    '',
    t.sticky,
    t.generated(src),
    ...(others.length ? [t.others([...new Set(others)].join(', '))] : []),
    '',
    role.body,
    '',
    t.team,
    ...team,
    '',
    t.direct,
    '<!-- flightwake-roles:end -->',
    '',
  ].join('\n');
}

/** Upsert (block) or strip (block = null) the role block in one file. Returns the action taken, or null. */
function writeBlock(path, block, dry) {
  const cur = existsSync(path) ? readFileSync(path, 'utf8') : null;
  let next;
  if (block) {
    if (cur === null) next = block;
    else if (ROLE_BLOCK_RE.test(cur)) next = cur.replace(ROLE_BLOCK_RE, `${block}\n`);
    else next = `${block}\n${cur}`; // role goes first: it is the first thing the agent should read
  } else {
    if (cur === null || !ROLE_BLOCK_RE.test(cur)) return null;
    next = cur.replace(ROLE_BLOCK_RE, '');
  }
  if (next === cur) return 'same';
  if (!dry) {
    if (!block && !next.trim()) { rmSync(path); return 'rm'; }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, next);
  }
  return cur === null ? 'add' : block ? 'update' : 'strip';
}

/** Find the team source when this repo has no ROLES.md of its own: read it back from an existing block's marker. */
function findSource(target) {
  const own = join(target, '.flightwake', 'ROLES.md');
  if (existsSync(own)) return own;
  for (const rels of Object.values(AGENT_FILES)) {
    for (const rel of rels) {
      const p = join(target, ...rel.split('/'));
      if (!existsSync(p)) continue;
      const m = /<!-- flightwake-roles:begin[^>]*\bsrc=(\S+)\s*-->/.exec(readFileSync(p, 'utf8'));
      if (m) {
        const s = decodeURI(m[1]);
        return isAbsolute(s) ? s : resolve(target, s);
      }
    }
  }
  return null;
}

export function removeRoleArtifacts(target, log) {
  for (const rels of Object.values(AGENT_FILES)) {
    for (const rel of rels) {
      const act = writeBlock(join(target, ...rel.split('/')), null, false);
      if (act === 'rm') log(`  rm   ${rel} (empty after role block removal)`);
      else if (act) log(`  edit ${rel} ← role block removed`);
    }
  }
  for (const base of SKILL_BASES) {
    const p = join(target, ...base.split('/'), 'fw-roles');
    if (existsSync(p)) { rmSync(p, { recursive: true }); log(`  rm   ${base}/fw-roles`); }
  }
}

/** On update: refresh the fw-roles skill wherever it is already installed (never installs it). */
export function refreshRolesSkill({ target, fwSrc, lang, noJunk, log }) {
  const src = join(fwSrc, 'addons', 'roles', ROLES_LANGS.includes(lang) ? lang : 'en', 'fw-roles');
  for (const base of SKILL_BASES) {
    const dst = join(target, ...base.split('/'), 'fw-roles');
    if (!existsSync(dst)) continue;
    rmSync(dst, { recursive: true });
    cpSync(src, dst, { recursive: true, filter: noJunk });
    log(`  update ${base}/fw-roles`);
  }
}

export function runRoles({ target, fwSrc, version, lang, args, log, M, noJunk }) {
  const sub = args.filter((a) => !a.startsWith('-'))[1] ?? 'install';
  const RL = ROLES_LANGS.includes(lang) ? lang : 'en';

  if (!existsSync(join(target, '.flightwake'))) {
    log(M({ en: '⚠️  No flightwake install here — run `npx flightwake init` first.', 'zh-TW': '⚠️  這裡沒有 flightwake 安裝 — 請先跑 `npx flightwake init`。' }));
    return 1;
  }

  if (sub === 'install') {
    const src = join(fwSrc, 'addons', 'roles', RL, 'fw-roles');
    const bases = ['.claude/skills', ...(['AGENTS.md', 'GEMINI.md'].some((f) => existsSync(join(target, f))) ? ['.agents/skills'] : [])];
    for (const base of bases) {
      const dst = join(target, ...base.split('/'), 'fw-roles');
      const existed = existsSync(dst);
      if (existed) rmSync(dst, { recursive: true });
      mkdirSync(dirname(dst), { recursive: true });
      cpSync(src, dst, { recursive: true, filter: noJunk });
      log(`  ${existed ? 'update' : 'add '} ${base}/fw-roles`);
    }
    if (RL !== lang) log(`  ℹ️  roles content ships in ${ROLES_LANGS.join(' / ')} for now — installed English`);
    log(M({
      en: '\n✅ fw-roles installed. Ask your agent to run fw-roles: it scans the project, recommends a team, lets you preview and customize, then runs `npx flightwake roles apply`.',
      'zh-TW': '\n✅ fw-roles 已安裝。請你的 agent 跑 fw-roles:它會掃專案、推薦一組角色、讓你預覽與客製,最後跑 `npx flightwake roles apply`。',
    }));
    return 0;
  }

  if (sub === 'remove') {
    removeRoleArtifacts(target, log);
    log(M({ en: '\n✅ role blocks and fw-roles removed. .flightwake/ROLES.md is user data and was kept.', 'zh-TW': '\n✅ 角色區塊與 fw-roles 已移除。.flightwake/ROLES.md 是使用者資料,保留。' }));
    return 0;
  }

  if (sub !== 'apply') {
    log(`⚠️  unknown roles subcommand: ${sub} (install | apply [--dry-run] | remove)`);
    return 1;
  }

  const DRY = args.includes('--dry-run');
  const source = findSource(target);
  if (!source || !existsSync(source)) {
    log(M({
      en: `⚠️  No .flightwake/ROLES.md here${source ? ` (block points to ${source}, which is missing)` : ''} — run the fw-roles skill to create one.`,
      'zh-TW': `⚠️  這裡沒有 .flightwake/ROLES.md${source ? `(區塊指向的 ${source} 不存在)` : ''} — 請跑 fw-roles skill 建立。`,
    }));
    return 1;
  }
  const home = dirname(dirname(source)); // <repo>/.flightwake/ROLES.md → <repo>
  const { roles, errors } = parseRoles(readFileSync(source, 'utf8'));
  errors.push(...planRoles(roles, home));
  if (errors.length) {
    log(`⚠️  ${relative(target, source) || source}:\n     ${errors.join('\n     ')}`);
    return 1;
  }

  log(`flightwake roles apply${DRY ? ' --dry-run' : ''} ← ${source}\n`);
  // Every repo in the team gets exactly its own roles; agents with no role there get their stale block stripped
  const repos = [...new Set([home, ...roles.map((r) => r.repoPath)])];
  for (const repo of repos) {
    for (const agent of Object.keys(AGENT_FILES)) {
      const role = roles.find((r) => r.repoPath === repo && r.agent === agent);
      const rel = fileFor(repo, agent);
      const path = join(repo, ...rel.split('/'));
      const block = role ? renderBlock(role, roles, { lang: RL, version, src: relative(repo, source) }) : null;
      const act = writeBlock(path, block, DRY);
      if (!act) continue;
      const label = repo === target ? rel : join(relative(target, repo) || '.', rel);
      log(`  ${act === 'same' ? 'same' : act.padEnd(4)} ${label}${role ? ` ← ${role.id}` : ''}`);
      if (DRY && block && act !== 'same') log(`\n${block.replace(/^/gm, '      ')}`);
    }
  }
  log(DRY
    ? M({ en: '\n(dry run — nothing written)', 'zh-TW': '\n(dry run — 未寫入任何檔案)' })
    : M({
      en: '\n✅ roles applied. Each agent picks its role up on its next new session or /clear. Commit the changed instruction files in every repo listed above.',
      'zh-TW': '\n✅ 角色已套用。每個 agent 在下一次新對話或 /clear 後生效。上面列到的每個 repo 都要 commit 變更的指令檔。',
    }));
  return 0;
}
